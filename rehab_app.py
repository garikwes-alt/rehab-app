sub_action = "Всі"
if selected_category not in ["Всі розділи", "Баланс"]:
    sub_action = st.sidebar.radio("Оберіть тип:", ["Всі", "Укріплення", "Розтяжка", "Тракція", "Укріплення та Розтяжка"])

keyword = st.sidebar.text_input("Або пошук за ключовим словом:")

